//! `atoll tokens`: export the theme's tokens as W3C Design Tokens (DTCG format 2025.10), one
//! file per colour mode, so a design tool (Figma variables, Tokens Studio, Penpot, Style
//! Dictionary) works from the same values as the code instead of a hand-copied palette.
//!
//! It reads the same tokens the contrast proof reads ([`Theme::parse`]: `:root` and
//! `[data-accent]` rules), picks each `light-dark()` side per mode, keeps a token that is only
//! `var(--other)` as an alias (`{other}`), and resolves the rest to plain values. Tokens that
//! aren't one colour, size, duration, number, easing or font stack (shadows, gradients, the
//! `--light`/`--dark` toggles) are left out and listed, since DTCG has no type for raw CSS.

use crate::contrast::{color, Ctx, Mode, Theme, Tokens};
use serde_json::{json, Map, Value};
use std::collections::BTreeMap;

/// One mode's export.
#[derive(Debug, Clone, PartialEq)]
pub struct Export {
    pub mode: Mode,
    /// The DTCG document: `{ "<token>": { "$type": .., "$value": .. }, .. }`.
    pub doc: Value,
    /// Tokens left out, with their resolved CSS.
    pub skipped: Vec<(String, String)>,
}

/// The tokens in effect: the theme's root tokens with `accent`'s preset over them.
fn layers<'a>(theme: &'a Theme, accent: Option<&str>) -> Result<Vec<&'a Tokens>, String> {
    let mut layers = Vec::new();
    if let Some(name) = accent.filter(|n| *n != "neutral") {
        let preset = theme
            .accents
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, t)| t)
            .ok_or_else(|| {
                format!(
                    "no accent preset `{name}`; the theme has: {}",
                    theme.accent_names().join(", ")
                )
            })?;
        layers.push(preset);
    }
    layers.push(&theme.root);
    Ok(layers)
}

/// Exports every token for one mode.
pub fn export(theme: &Theme, accent: Option<&str>, mode: Mode) -> Result<Export, String> {
    let layers = layers(theme, accent)?;
    let ctx = Ctx {
        mode,
        layers: layers.clone(),
    };
    let mut names = BTreeMap::new();
    for t in layers.iter().rev() {
        for (k, v) in &t.vars {
            names.insert(k.clone(), v.clone());
        }
    }
    let mut doc = Map::new();
    let mut skipped = Vec::new();
    for (name, raw) in &names {
        if name == "--light" || name == "--dark" {
            continue;
        }
        let key = name.trim_start_matches("--").to_string();
        let picked = pick_mode(raw.trim(), mode);
        // `var(--x)` alone stays a reference, so the design tool keeps the link.
        if let Some(target) = lone_var(&picked).filter(|t| names.contains_key(*t)) {
            let target_key = target.trim_start_matches("--");
            if let Some(kind) = ctx.substitute(&picked, 0).and_then(|v| typed(name, &v)) {
                doc.insert(
                    key,
                    json!({ "$type": kind.0, "$value": format!("{{{target_key}}}") }),
                );
                continue;
            }
        }
        match ctx.substitute(&picked, 0) {
            Some(v) => match typed(name, &v) {
                Some((kind, value)) => {
                    doc.insert(key, json!({ "$type": kind, "$value": value }));
                }
                None => skipped.push((key, v.trim().to_string())),
            },
            None => skipped.push((key, raw.clone())),
        }
    }
    let mut root = Map::new();
    root.insert(
        "$description".into(),
        Value::String(format!(
            "Atoll theme tokens, {} mode{}. Generated by `atoll tokens`; edit theme.css, not this file.",
            mode.name(),
            accent
                .filter(|a| *a != "neutral")
                .map(|a| format!(", accent `{a}`"))
                .unwrap_or_default()
        )),
    );
    root.extend(doc);
    Ok(Export {
        mode,
        doc: Value::Object(root),
        skipped,
    })
}

/// A top-level `light-dark(a, b)` becomes `a` or `b`; anything else is kept.
fn pick_mode(raw: &str, mode: Mode) -> String {
    if let Some(inner) = raw
        .strip_prefix("light-dark(")
        .and_then(|s| s.strip_suffix(')'))
    {
        let parts = split_top(inner);
        if parts.len() == 2 {
            return match mode {
                Mode::Light => parts[0].trim().to_string(),
                Mode::Dark => parts[1].trim().to_string(),
            };
        }
    }
    raw.to_string()
}

/// `var(--x)` with no fallback and nothing around it.
fn lone_var(v: &str) -> Option<&str> {
    let inner = v.trim().strip_prefix("var(")?.strip_suffix(')')?.trim();
    (inner.starts_with("--") && !inner.contains([',', '(', ' '])).then_some(inner)
}

/// Commas at nesting depth 0.
fn split_top(s: &str) -> Vec<&str> {
    let (mut depth, mut start, mut out) = (0i32, 0, Vec::new());
    for (i, c) in s.char_indices() {
        match c {
            '(' => depth += 1,
            ')' => depth -= 1,
            ',' if depth == 0 => {
                out.push(&s[start..i]);
                start = i + 1;
            }
            _ => {}
        }
    }
    out.push(&s[start..]);
    out
}

/// The DTCG type and value of a resolved CSS value, if it has one.
fn typed(name: &str, v: &str) -> Option<(&'static str, Value)> {
    let v = v.trim();
    if v.is_empty() {
        return None;
    }
    if let Some(c) = color(v) {
        return Some(("color", Value::String(c.hex())));
    }
    if let Some((value, unit)) = number_with_unit(v) {
        return match unit {
            "px" | "rem" => Some(("dimension", json!({ "value": value, "unit": unit }))),
            // `em` has no DTCG unit; at the root it is the same as rem.
            "em" => Some(("dimension", json!({ "value": value, "unit": "rem" }))),
            "ms" => Some(("duration", json!({ "value": value, "unit": "ms" }))),
            "s" => Some(("duration", json!({ "value": value * 1000.0, "unit": "ms" }))),
            "" if value == 0.0 && is_size_name(name) => {
                Some(("dimension", json!({ "value": 0, "unit": "px" })))
            }
            "" => Some(("number", json!(value))),
            _ => None,
        };
    }
    if let Some(inner) = v
        .strip_prefix("cubic-bezier(")
        .and_then(|s| s.strip_suffix(')'))
    {
        let n: Vec<f64> = split_top(inner)
            .iter()
            .filter_map(|p| p.trim().parse().ok())
            .collect();
        if n.len() == 4 {
            return Some(("cubicBezier", json!(n)));
        }
    }
    if name.contains("font") && !name.contains("size") && !name.contains("weight") {
        let fonts: Vec<String> = split_top(v)
            .iter()
            .map(|f| f.trim().trim_matches(['"', '\'']).to_string())
            .filter(|f| !f.is_empty() && !f.contains('('))
            .collect();
        if !fonts.is_empty() {
            return Some(("fontFamily", json!(fonts)));
        }
    }
    None
}

fn is_size_name(name: &str) -> bool {
    [
        "radius", "space", "size", "width", "height", "gap", "padding", "offset",
    ]
    .iter()
    .any(|w| name.contains(w))
}

/// `0.5rem` -> (0.5, "rem"); `400` -> (400, "").
fn number_with_unit(v: &str) -> Option<(f64, &str)> {
    let split = v
        .find(|c: char| !(c.is_ascii_digit() || c == '.' || c == '-' || c == '+'))
        .unwrap_or(v.len());
    let (num, unit) = v.split_at(split);
    let value: f64 = num.parse().ok()?;
    unit.chars()
        .all(|c| c.is_ascii_alphabetic())
        .then_some((value, unit))
}

#[cfg(test)]
mod tests {
    use super::*;

    const CSS: &str = r#"
:root {
  --light: initial;
  --primary-color: light-dark(#fff, #000);
  --accent-color: var(--primary-color);
  --accent-contrast: light-dark(var(--primary-color), #123456);
  --overlay-color: light-dark(rgb(0 0 0 / 40%), rgb(0 0 0 / 60%));
  --radius: 0.5rem;
  --space-0: 0;
  --duration-fast: 150ms;
  --ease-out: cubic-bezier(0.2, 0, 0, 1);
  --font-sans: "Inter", system-ui, sans-serif;
  --shadow-1: 0 1px 2px rgb(0 0 0 / 10%);
}
[data-accent="blue"] {
  --accent-color: light-dark(#2563eb, #60a5fa);
}
"#;

    fn get<'a>(e: &'a Export, k: &str) -> &'a Value {
        &e.doc[k]
    }

    #[test]
    fn colours_pick_their_mode() {
        let theme = Theme::parse(CSS);
        let light = export(&theme, None, Mode::Light).unwrap();
        let dark = export(&theme, None, Mode::Dark).unwrap();
        assert_eq!(get(&light, "primary-color")["$value"], "#ffffff");
        assert_eq!(get(&dark, "primary-color")["$value"], "#000000");
        assert_eq!(get(&light, "primary-color")["$type"], "color");
        assert_eq!(get(&dark, "accent-contrast")["$value"], "#123456");
        assert_eq!(get(&light, "overlay-color")["$value"], "#00000066");
    }

    #[test]
    fn a_lone_var_stays_an_alias() {
        let theme = Theme::parse(CSS);
        let light = export(&theme, None, Mode::Light).unwrap();
        assert_eq!(get(&light, "accent-color")["$value"], "{primary-color}");
        assert_eq!(get(&light, "accent-color")["$type"], "color");
        // Only one side of light-dark() is a reference.
        assert_eq!(get(&light, "accent-contrast")["$value"], "{primary-color}");
    }

    #[test]
    fn sizes_times_easings_and_fonts_are_typed() {
        let e = export(&Theme::parse(CSS), None, Mode::Light).unwrap();
        assert_eq!(
            get(&e, "radius"),
            &json!({ "$type": "dimension", "$value": { "value": 0.5, "unit": "rem" } })
        );
        assert_eq!(
            get(&e, "space-0")["$value"],
            json!({ "value": 0, "unit": "px" })
        );
        assert_eq!(get(&e, "duration-fast")["$type"], "duration");
        assert_eq!(get(&e, "ease-out")["$value"], json!([0.2, 0.0, 0.0, 1.0]));
        assert_eq!(
            get(&e, "font-sans")["$value"],
            json!(["Inter", "system-ui", "sans-serif"])
        );
    }

    #[test]
    fn untyped_tokens_and_toggles_are_left_out() {
        let e = export(&Theme::parse(CSS), None, Mode::Light).unwrap();
        assert!(e.doc.get("shadow-1").is_none());
        assert!(e.doc.get("light").is_none());
        assert!(e.skipped.iter().any(|(k, _)| k == "shadow-1"));
    }

    #[test]
    fn an_accent_preset_overrides_the_root() {
        let theme = Theme::parse(CSS);
        let dark = export(&theme, Some("blue"), Mode::Dark).unwrap();
        assert_eq!(get(&dark, "accent-color")["$value"], "#60a5fa");
        assert!(export(&theme, Some("nope"), Mode::Dark).is_err());
    }

    /// The kit's own theme exports, with every colour token typed in both modes.
    #[test]
    fn the_kit_theme_exports() {
        let css = std::fs::read_to_string(
            std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../ui/assets/theme.css"),
        )
        .unwrap();
        let theme = Theme::parse(&css);
        for mode in Mode::ALL {
            let e = export(&theme, None, mode).unwrap();
            for key in [
                "primary-color",
                "secondary-color-4",
                "accent-color",
                "radius",
            ] {
                assert!(
                    e.doc.get(key).is_some(),
                    "{key} missing in {}: skipped {:?}",
                    mode.name(),
                    e.skipped
                );
            }
            for (k, v) in e.doc.as_object().unwrap() {
                if k.ends_with("-color") {
                    assert_eq!(v["$type"], "color", "{k} in {}", mode.name());
                }
            }
        }
    }
}
