//! Generates `apps/docs/src/generated.rs`: every component's docs page source and a match from
//! component name to its live demo. Like `registry.json` it is generated, and a test fails
//! when it is stale, so the docs site can't drift from the components.

use crate::contract::Contract;
use crate::{build, COMPONENTS_DIR, DEMOS_DIR};
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

pub const OUTPUT: &str = "apps/docs/src/generated.rs";

/// The `# Title` line of a docs page, falling back to the humanised component name
/// (`alert_dialog` -> `Alert dialog`).
pub fn title(docs: &str, name: &str) -> String {
    docs.lines()
        .find_map(|l| l.strip_prefix("# "))
        .map(|t| t.trim().to_string())
        .unwrap_or_else(|| {
            let spaced = name.replace('_', " ");
            let mut chars = spaced.chars();
            chars
                .next()
                .map(|c| c.to_uppercase().collect::<String>() + chars.as_str())
                .unwrap_or_default()
        })
}

pub fn generate(root: &Path) -> io::Result<String> {
    let reg = build(root)?;
    let mut entries = String::new();
    let mut arms = String::new();
    for item in reg.items.iter().filter(|i| i.kind.is_component()) {
        let name = &item.name;
        let docs_path = root.join(COMPONENTS_DIR).join(name).join("docs.md");
        let docs = fs::read_to_string(&docs_path).unwrap_or_default();
        let has_demo = root.join(DEMOS_DIR).join(format!("{name}.rs")).is_file();
        // The keyboard table generated from contract.toml, shown after the docs.
        let contract = Contract::load(&root.join(COMPONENTS_DIR), name)
            .map_err(io::Error::other)?
            .map(|c| c.markdown())
            .unwrap_or_default();
        entries.push_str(&format!(
            "    Entry {{ name: {name:?}, title: {:?}, docs: include_str!(\"../../../{COMPONENTS_DIR}/{name}/docs.md\"), contract: {contract:?}, has_demo: {has_demo} }},\n",
            title(&docs, name)
        ));
        if has_demo {
            arms.push_str(&format!(
                "        {name:?} => rsx! {{ ui::demos::{name}::Demo {{}} }},\n"
            ));
        }
    }
    Ok(format!(
        "// @generated by `atoll registry`. Do not edit.\n\
         use dioxus::prelude::*;\n\n\
         pub struct Entry {{\n    pub name: &'static str,\n    pub title: &'static str,\n    pub docs: &'static str,\n    /// The keyboard and accessibility section generated from `contract.toml` (may be empty).\n    pub contract: &'static str,\n    pub has_demo: bool,\n}}\n\n\
         pub const ENTRIES: &[Entry] = &[\n{entries}];\n\n\
         /// The live demo for a component, or nothing when it has none.\n\
         pub fn demo(name: &str) -> Element {{\n    match name {{\n{arms}        _ => rsx! {{}},\n    }}\n}}\n"
    ))
}

pub fn write(root: &Path) -> io::Result<PathBuf> {
    let path = root.join(OUTPUT);
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(&path, generate(root)?)?;
    Ok(path)
}

pub fn is_stale(root: &Path) -> io::Result<bool> {
    Ok(fs::read_to_string(root.join(OUTPUT)).ok().as_deref() != Some(generate(root)?.as_str()))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn title_comes_from_the_first_heading() {
        assert_eq!(
            title("# Alert dialog\n\ntext", "alert_dialog"),
            "Alert dialog"
        );
        assert_eq!(title("no heading", "alert_dialog"), "Alert dialog");
    }
}
